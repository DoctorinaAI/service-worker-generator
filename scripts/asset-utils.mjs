/**
 * [js] as a Dart string literal that holds exactly those bytes.
 *
 * Raw triple-quoted (`r'''…'''`) because the bundles are minified JS, full
 * of backslashes and `$`: escaping all of those would make the generated
 * file both larger and harder to read. Two sequences cannot appear inside
 * such a literal, so they are spliced in as ordinary quoted pieces and the
 * whole thing is a concatenation:
 *
 *   - `'''` would close the literal early. The previous renderer wrote
 *     `\'\'\' ` instead, which inside a *raw* string is five literal
 *     characters, not three: the embedded JS came out different from the
 *     bundle, and the verifier — which renders the same way — agreed with
 *     it.
 *   - a `'` at the very end of a chunk would run into the closing `'''`
 *     and leave a stray quote, which does not compile at all.
 *
 * Today's bundles contain neither; both are one upstream change away.
 */
function dartStringLiteral(js) {
  const pieces = [];
  const chunks = js.split("'''");
  chunks.forEach((chunk, index) => {
    // Quotes at either end of a chunk go in as a quoted piece: inside the
    // raw literal they would touch its delimiters.
    const lead = /^'*/.exec(chunk)[0];
    let body = chunk.slice(lead.length);
    const tail = /'*$/.exec(body)[0];
    body = body.slice(0, body.length - tail.length);
    if (lead) pieces.push(JSON.stringify(lead));
    if (body) pieces.push(`r'''\n${body}'''`);
    if (tail) pieces.push(JSON.stringify(tail));
    if (index < chunks.length - 1) pieces.push(`"'''"`);
  });
  return pieces.length > 0 ? pieces.join('\n    ') : "''";
}

export function renderDartAsset({ input, constName, description }, js) {
  const dartContent = dartStringLiteral(js);

  return `// GENERATED FILE - DO NOT EDIT
// Generated by scripts/copy-assets.mjs
// Source: ${input}

/// ${description}
/// Contains placeholder tokens that the CLI replaces with actual
/// configuration at generation time.
const String ${constName} = ${dartContent};
`;
}

export function normalizeTextForComparison(text) {
  return text.replace(/\r\n/g, '\n');
}
